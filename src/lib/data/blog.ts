const gradients: [string, string][] = [
  ["#232f3e", "#37475a"],
  ["#0f4c5c", "#146b7e"],
  ["#5c1f0f", "#8a3b1f"],
  ["#1f3a5c", "#2f5a8a"],
  ["#3a1f5c", "#5a2f8a"],
  ["#1f5c3a", "#2f8a5a"],
];

export const blogPosts: BlogPost[] = raw.map((p, i) => ({
  ...p,
  id: `blog-${i + 1}`,
  slug: `blog-${i + 1}`,
  colorFrom: gradients[i % gradients.length][0],
  colorTo: gradients[i % gradients.length][1],
}));

export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((p) => p.slug === slug);
}
